    /// FNV-1a (64-bit), so the digests below need no dependency and no
    /// `unsafe`. It is not a cryptographic hash and is not being used as one:
    /// it guards against an accidental edit, not against a forged one.
    fn fnv1a64(bytes: &[u8]) -> u64 {
        let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
        for byte in bytes {
            hash ^= u64::from(*byte);
            hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
        }
        hash
    }

    /// Pins the divergence in `docs/divergences.md`: these three files are
    /// compiled in, so a cluster gets *these* bytes and never the ones in a
    /// host's `share/`. What upstream ships is therefore part of this crate's
    /// observable behaviour, and drifting from it has to be a deliberate act.
    ///
    /// A failure here means a template changed. That is legitimate when
    /// PostgreSQL 18.x changes one — re-vendor from upstream (tag `REL_18_6`
    /// or the published tarball, never pgrust's tree; see ADR-0007), update
    /// the digest, and say so on the Linear issue — and is a bug in every
    /// other case, including a stray editor reformat or a line-ending
    /// conversion. The lengths are asserted too so the failure says *which*
    /// file and by how much.
    ///
    /// A digest proves only "unchanged since someone pinned it", never
    /// "upstream's". It is computed *from* the file, so whatever bytes were
    /// vendored are the bytes it blesses — which is how a pgrust-modified
    /// `postgresql.conf.sample` shipped here and passed. The tests below
    /// assert against expectations written down from upstream instead —
    /// upstream's own SHA-256 of each file, its section banners, and the
    /// absence of any namespaced setting.
    #[test]
    fn the_embedded_templates_are_the_postgresql_18_6_bytes_we_vendored() {
        for (name, sample, length, digest) in [
            (
                "postgresql.conf.sample",
                POSTGRESQL_CONF_SAMPLE,
                32_652,
                0x364a_ac11_a839_c67f_u64,
            ),
            (
                "pg_hba.conf.sample",
                PG_HBA_CONF_SAMPLE,
                5_635,
                0x0a0d_1bd3_d9f1_4f98,
            ),
            (
                "pg_ident.conf.sample",
                PG_IDENT_CONF_SAMPLE,
                2_681,
                0xda9b_59c0_b8dd_0769,
            ),
        ] {
            assert_eq!(sample.len(), length, "{name} changed length");
            assert_eq!(fnv1a64(sample.as_bytes()), digest, "{name} changed content");
        }
    }

