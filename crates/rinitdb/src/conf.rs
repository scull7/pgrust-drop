/// `initdb.c:1326` — the date order `locale_date_order()` (`:2143`) reports for
/// `lc_time`, and so which `DateStyle` the cluster gets.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum DateOrder {
    /// `DATEORDER_YMD` → `iso, ymd`.
    Ymd,
    /// `DATEORDER_DMY` → `iso, dmy`.
    Dmy,
    /// `DATEORDER_MDY` → `iso, mdy`. Upstream's `result = DATEORDER_MDY;
    /// /* default */` (`:2153`), which is also what every early return keeps.
    #[default]
    Mdy,
}

impl DateOrder {
    /// The `datestyle` value for this order (`initdb.c:1328`, `:1331`, `:1335`).
    #[must_use]
    pub fn datestyle(self) -> &'static str {
        match self {
            Self::Ymd => "iso, ymd",
            Self::Dmy => "iso, dmy",
            Self::Mdy => "iso, mdy",
        }
    }
}

/// The resolved `authmethodlocal` / `authmethodhost` pair (`initdb.c:157`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AuthMethods {
    /// `authmethodlocal`, substituted for `@authmethodlocal@`.
    pub local: String,
    /// `authmethodhost`, substituted for `@authmethodhost@`.
    pub host: String,
}

impl Default for AuthMethods {
    /// Both unspecified, so both `trust` (`check_authmethod_unspecified`,
    /// `initdb.c:2572`).
    fn default() -> Self {
        Self {
            local: String::from("trust"),
            host: String::from("trust"),
        }
    }
}

impl AuthMethods {
    /// `initdb.c:3246` (the `-A` arm) followed by `check_authmethod_unspecified`
    /// (`:3457`, `:3458`).
    ///
    /// `-A` sets both sides, with upstream's two mirrored special cases: `ident`
    /// is meaningless on a Unix socket so the local side becomes `peer`, and
    /// `peer` is meaningless over TCP/IP so the host side becomes `ident`.
    /// `--auth-local` and `--auth-host` then override their own side.
    ///
    /// Divergence (`docs/divergences.md`): C's getopt applies the three
    /// switches in command-line order, so a `-A` written *after* `--auth-host`
    /// wins there and loses here. usage-rs reports which switches were given,
    /// not where.
    #[must_use]
    pub fn resolve(options: &Options) -> Self {
        let mut methods = Self::default();
        if let Some(both) = options.auth.as_deref() {
            both.clone_into(&mut methods.local);
            both.clone_into(&mut methods.host);
            if methods.host == "ident" {
                methods.local = String::from("peer");
            } else if methods.local == "peer" {
                methods.host = String::from("ident");
            }
        }
        if let Some(local) = options.auth_local.as_deref() {
            local.clone_into(&mut methods.local);
        }
        if let Some(host) = options.auth_host.as_deref() {
            host.clone_into(&mut methods.host);
        }
        methods
    }

    /// `initdb.c:1518` — `@authcomment@` is the warning when either side trusts.
    #[must_use]
    pub fn auth_comment(&self) -> &'static str {
        if self.local == "trust" || self.host == "trust" {
            AUTHTRUST_WARNING
        } else {
            ""
        }
    }

    /// `initdb.c:1406` — md5 on one side, and not scram-sha-256 on the other,
    /// drags `password_encryption` back to md5.
    #[must_use]
    pub fn forces_md5_password_encryption(&self) -> bool {
        (self.local == "md5" && self.host != "scram-sha-256")
            || (self.host == "md5" && self.local != "scram-sha-256")
    }
}

