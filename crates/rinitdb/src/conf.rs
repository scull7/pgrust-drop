/// `pretty_wal_size()` (`initdb.c:1266`): `segment_count` segments as `GB` when
/// that is a whole number of gigabytes, otherwise `MB`.
#[must_use]
pub fn pretty_wal_size(segment_count: u32, wal_segment_size_mb: u32) -> String {
    let size = wal_segment_size_mb * segment_count;
    if size.is_multiple_of(1024) {
        format!("{}GB", size / 1024)
    } else {
        format!("{size}MB")
    }
}

/// `initdb.c:1310`: `n_buffers` blocks as `MB` when that is a whole number of
/// megabytes, otherwise `kB`.
#[must_use]
pub fn shared_buffers_value(n_buffers: u32) -> String {
    let kilobytes = n_buffers * (pg_config::BLCKSZ / 1024);
    if kilobytes.is_multiple_of(1024) {
        format!("{}MB", kilobytes / 1024)
    } else {
        format!("{kilobytes}kB")
    }
}

/// `initdb.c:1377`: a flush-after default, measured in blocks, rendered in kB.
#[must_use]
pub fn flush_after_value(blocks: u32) -> String {
    format!("{}kB", blocks * (pg_config::BLCKSZ / 1024))
}

