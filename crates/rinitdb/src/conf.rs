//! `setup_config()` (`initdb.c:1283`): the four configuration files a new
//! cluster gets, as pure functions over the vendored `.sample` templates.
//!
//! Everything here is a calculation. The templates are compiled in with
//! `include_str!` (ADR-0002: there is no `share/` directory on the host to read
//! them from), the values `setup_config` would have probed for arrive as
//! [`Settings`], and each `render_*` returns the exact bytes upstream's
//! `writefile` would have written. Creating the files, and probing the machine
//! for the values, are separate and live elsewhere.
//!
//! The two string surgeons are upstream's, transcribed rather than reimagined:
//! [`replace_token`] (`initdb.c:473`) rewrites the first occurrence of a literal
//! on each line, and [`replace_guc_value`] (`initdb.c:528`) rewrites a
//! possibly-commented-out assignment, keeping the file's spelling of the
//! parameter name and re-aligning any trailing comment. Neither uses a regular
//! expression, exactly as upstream notes: "this does most of what sed was used
//! for in the shell script, but doesn't need any regexp stuff".

use crate::cli::Options;
use crate::file_perm::{DataDirPerm, PG_DIR_MODE_GROUP};
