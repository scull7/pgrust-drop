/// `setup_config`'s `postgresql.conf` half (`initdb.c:1289`-`:1439`), in
/// upstream's order — which matters, because a `-c` override re-aligns the
/// comment on a line an earlier replacement has already rewritten.
#[must_use]
pub fn render_postgresql_conf(sample: &str, settings: &Settings) -> String {
    let mut lines = split_lines(sample);

    let set = |lines, name: &str, value: &str| replace_guc_value(lines, name, value, false);
    let comment = |lines, name: &str, value: &str| replace_guc_value(lines, name, value, true);

    lines = set(
        lines,
        "max_connections",
        &settings.max_connections.to_string(),
    );
    lines = set(
        lines,
        "autovacuum_worker_slots",
        &settings.autovacuum_worker_slots.to_string(),
    );
    lines = set(
        lines,
        "shared_buffers",
        &shared_buffers_value(settings.shared_buffers_blocks),
    );
    lines = set(lines, "lc_messages", &settings.lc_messages);
    lines = set(lines, "lc_monetary", &settings.lc_monetary);
    lines = set(lines, "lc_numeric", &settings.lc_numeric);
    lines = set(lines, "lc_time", &settings.lc_time);
    lines = set(lines, "datestyle", settings.date_order.datestyle());
    lines = set(
        lines,
        "default_text_search_config",
        &format!("pg_catalog.{}", settings.default_text_search_config),
    );
    if let Some(timezone) = settings.default_timezone.as_deref() {
        lines = set(lines, "timezone", timezone);
        lines = set(lines, "log_timezone", timezone);
    }
    lines = set(
        lines,
        "dynamic_shared_memory_type",
        &settings.dynamic_shared_memory_type,
    );

    // "Caution: these depend on wal_segment_size_mb, they're not constants"
    lines = set(
        lines,
        "min_wal_size",
        &pretty_wal_size(
            pg_config::DEFAULT_MIN_WAL_SEGS,
            settings.wal_segment_size_mb,
        ),
    );
    lines = set(
        lines,
        "max_wal_size",
        &pretty_wal_size(
            pg_config::DEFAULT_MAX_WAL_SEGS,
            settings.wal_segment_size_mb,
        ),
    );

    // Entries fixed up to the true compile-time defaults stay commented.
    lines = comment(
        lines,
        "unix_socket_directories",
        pg_config::DEFAULT_PGSOCKET_DIR,
    );
    lines = comment(lines, "port", pg_config::DEF_PGPORT_STR);
    for (name, blocks) in pg_config::FLUSH_AFTER_DEFAULTS {
        if blocks > 0 {
            lines = comment(lines, name, &flush_after_value(blocks));
        }
    }
    if pg_config::UPDATE_PROCESS_TITLE_OFF {
        lines = comment(lines, "update_process_title", "off");
    }

    if settings.auth.forces_md5_password_encryption() {
        lines = set(lines, "password_encryption", "md5");
    }
    if settings.perm.dir_mode == PG_DIR_MODE_GROUP {
        lines = set(lines, "log_file_mode", "0640");
    }

    // "Now replace anything that's overridden via -c switches."
    for (name, value) in &settings.gucs {
        lines = set(lines, name, value);
    }

    join_lines(&lines)
}

/// `initdb.c:1443` — `postgresql.auto.conf` is two literal lines.
#[must_use]
pub fn render_postgresql_auto_conf() -> String {
    POSTGRESQL_AUTO_CONF.to_owned()
}

/// `setup_config`'s `pg_hba.conf` half (`initdb.c:1460`-`:1519`).
#[must_use]
pub fn render_pg_hba_conf(sample: &str, settings: &Settings) -> String {
    let mut lines = split_lines(sample);

    lines = replace_token(lines, "@remove-line-for-nolocal@", "");

    // Without platform support for IPv6, comment out the two `::1` records.
    if !settings.ipv6_supported {
        lines = replace_token(
            lines,
            "host    all             all             ::1",
            "#host    all             all             ::1",
        );
        lines = replace_token(
            lines,
            "host    replication     all             ::1",
            "#host    replication     all             ::1",
        );
    }

    lines = replace_token(lines, "@authmethodhost@", &settings.auth.host);
    lines = replace_token(lines, "@authmethodlocal@", &settings.auth.local);
    lines = replace_token(lines, "@authcomment@", settings.auth.auth_comment());

    join_lines(&lines)
}

