/// C's `isspace()` in the "C" locale, which includes the vertical tab Rust's
/// [`u8::is_ascii_whitespace`] leaves out.
fn is_c_space(byte: u8) -> bool {
    matches!(byte, b' ' | b'\t' | b'\n' | 0x0b | 0x0c | b'\r')
}

/// `pg_strncasecmp(a, b, n) == 0`, over the first `n` bytes.
fn starts_with_ignoring_ascii_case(haystack: &[u8], needle: &[u8]) -> bool {
    haystack.len() >= needle.len() && haystack[..needle.len()].eq_ignore_ascii_case(needle)
}

/// `readfile()` (`initdb.c:676`): the file as lines, each keeping its own
/// newline, and a final line without one kept as it is.
///
/// Upstream reads with `pg_get_line_buf`, which keeps the terminator; the
/// round trip through [`join_lines`] is therefore the identity.
#[must_use]
pub fn split_lines(text: &str) -> Vec<String> {
    let mut lines = Vec::new();
    let mut rest = text;
    while !rest.is_empty() {
        if let Some(end) = rest.find('\n') {
            lines.push(rest[..=end].to_owned());
            rest = &rest[end + 1..];
        } else {
            lines.push(rest.to_owned());
            break;
        }
    }
    lines
}

/// `writefile()` (`initdb.c:723`): the lines `fputs`'d back out, nothing added.
#[must_use]
pub fn join_lines(lines: &[String]) -> String {
    lines.concat()
}

/// `replace_token()` (`initdb.c:473`): replace `token` with `replacement` the
/// **first** time it occurs on each line.
#[must_use]
pub fn replace_token(lines: Vec<String>, token: &str, replacement: &str) -> Vec<String> {
    lines
        .into_iter()
        .map(|line| match line.find(token) {
            None => line,
            Some(at) => {
                let mut new = String::with_capacity(line.len() + replacement.len());
                new.push_str(&line[..at]);
                new.push_str(replacement);
                new.push_str(&line[at + token.len()..]);
                new
            }
        })
        .collect()
}

/// `guc_value_requires_quotes()` (`initdb.c:644`): identifiers and numbers with
/// optional unit letters go in bare; everything else is quoted.
#[must_use]
pub fn guc_value_requires_quotes(value: &str) -> bool {
    let bytes = value.as_bytes();
    let Some(&first) = bytes.first() else {
        return true; // empty string must be quoted
    };
    if first.is_ascii_alphabetic() {
        // an identifier: letters and digits all the way down
        return !bytes.iter().all(u8::is_ascii_alphanumeric);
    }
    if first.is_ascii_digit() {
        // a number, then zero or more unit letters
        let after_digits = bytes
            .iter()
            .position(|b| !b.is_ascii_digit())
            .unwrap_or(bytes.len());
        return !bytes[after_digits..].iter().all(u8::is_ascii_alphabetic);
    }
    true // all else must be quoted
}

/// `escape_quotes()` (`initdb.c:406`) via `escape_single_quotes_ascii()`
/// (`src/port/quotes.c:34`): double every single quote and every backslash.
#[must_use]
pub fn escape_quotes(src: &str) -> String {
    let mut out = String::with_capacity(src.len());
    for ch in src.chars() {
        if ch == '\'' || ch == '\\' {
            out.push(ch);
        }
        out.push(ch);
    }
    out
}

/// The prepared replacement line, before the comment and the newline:
/// `[#]name = value`, with the value quoted if it has to be.
fn prepared_assignment(guc_name: &str, guc_value: &str, mark_as_comment: bool) -> String {
    let mut line = String::new();
    if mark_as_comment {
        line.push('#');
    }
    line.push_str(guc_name);
    line.push_str(" = ");
    if guc_value_requires_quotes(guc_value) {
        line.push('\'');
        line.push_str(&escape_quotes(guc_value));
        line.push('\'');
    } else {
        line.push_str(guc_value);
    }
    line
}

/// A line of the template that assigns `guc_name`, located the way
/// `replace_guc_value` locates one (`initdb.c:547`-`:563`): skip any mix of
/// `#` and whitespace, match the name case-insensitively, skip whitespace
/// again, and require an `=`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct Assignment {
    /// Byte offset of the name as the *file* spells it, for the canonical
    /// casing `initdb.c:566` copies over the prepared line.
    name_start: usize,
    /// Byte offset of the `=`, where upstream's `strrchr(where, '#')` for the
    /// trailing comment starts.
    equals_at: usize,
}

fn find_assignment(line: &str, guc_name: &str) -> Option<Assignment> {
    let bytes = line.as_bytes();
    let mut at = 0;
    while at < bytes.len() && (bytes[at] == b'#' || is_c_space(bytes[at])) {
        at += 1;
    }
    if !starts_with_ignoring_ascii_case(&bytes[at..], guc_name.as_bytes()) {
        return None;
    }
    let name_start = at;
    at += guc_name.len();
    while at < bytes.len() && is_c_space(bytes[at]) {
        at += 1;
    }
    if bytes.get(at) != Some(&b'=') {
        return None;
    }
    Some(Assignment {
        name_start,
        equals_at: at,
    })
}

/// De-tabified column of byte offset `upto`, tab stops every 8 columns
/// (`initdb.c:618`).
fn detabified_column(line: &str, upto: usize) -> usize {
    let mut column = 0;
    for &byte in &line.as_bytes()[..upto] {
        if byte == b'\t' {
            column += 8 - (column % 8);
        } else {
            column += 1;
        }
    }
    column
}

/// `replace_guc_value()` (`initdb.c:528`): replace the possibly-commented-out
/// assignment of `guc_name` with a live assignment of `guc_value`, appending a
/// new line when the file has no such assignment at all.
///
/// The match is case-insensitive and the **file's** spelling of the name is
/// what gets written (`initdb.c:566`), so `-c WORK_MEM=512` produces
/// `work_mem = 512`. Only the first match is replaced ("we assume there's at
/// most one matching assignment"), and any trailing comment is carried over at
/// its original de-tabified column.
#[must_use]
pub fn replace_guc_value(
    mut lines: Vec<String>,
    guc_name: &str,
    guc_value: &str,
    mark_as_comment: bool,
) -> Vec<String> {
    let prepared = prepared_assignment(guc_name, guc_value, mark_as_comment);

    for line in &mut lines {
        let Some(found) = find_assignment(line, guc_name) else {
            continue;
        };

        // "found it -- let's use the canonical casing shown in the file": the
        // name sits at offset 0, or 1 past the '#', of the prepared line.
        let name_start = usize::from(mark_as_comment);
        let file_spelling = &line[found.name_start..found.name_start + guc_name.len()];
        let mut new = prepared.clone();
        new.replace_range(name_start..name_start + guc_name.len(), file_spelling);

        match line[found.equals_at..]
            .rfind('#')
            .map(|at| found.equals_at + at)
        {
            Some(comment_at) => {
                // Preserve the comment's column, forcing at least one space.
                let old_indent = detabified_column(line, comment_at);
                let mut new_indent = new.len();
                let target = old_indent.max(new_indent + 1);
                while new_indent < target {
                    let if_tab = new_indent + 8 - (new_indent % 8);
                    if if_tab <= target {
                        new.push('\t');
                        new_indent = if_tab;
                    } else {
                        new.push(' ');
                        new_indent += 1;
                    }
                }
                // The old comment carries the original newline with it.
                new.push_str(&line[comment_at..]);
            }
            None => new.push('\n'),
        }

        *line = new;
        return lines; // "assume there's only one match"
    }

    // No match, so append a new entry.
    lines.push(prepared + "\n");
    lines
}

