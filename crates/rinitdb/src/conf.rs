    fn a_trailing_dash_a_does_not_win_over_a_per_side_switch() {
        // C's getopt, given `--auth-host md5 -A trust`, ends with host=trust.
        let methods = AuthMethods::resolve(&options_with(Some("trust"), None, Some("md5")));
        assert_eq!(methods.host, "md5", "the per-side switch always wins here");
    }

    #[test]
    fn trust_on_either_side_brings_the_caution_block() {
        for (local, host) in [("trust", "trust"), ("trust", "md5"), ("peer", "trust")] {
            let methods = AuthMethods {
                local: local.to_owned(),
                host: host.to_owned(),
            };
            assert_eq!(methods.auth_comment(), AUTHTRUST_WARNING);
        }
        let methods = AuthMethods {
            local: String::from("peer"),
            host: String::from("scram-sha-256"),
        };
        assert_eq!(methods.auth_comment(), "");
    }

    #[test]
    fn md5_on_one_side_drags_password_encryption_back_unless_scram_is_on_the_other() {
        let md5 = |local: &str, host: &str| {
            AuthMethods {
                local: local.to_owned(),
                host: host.to_owned(),
            }
            .forces_md5_password_encryption()
        };
        assert!(md5("md5", "md5"));
        assert!(md5("md5", "trust"));
        assert!(md5("peer", "md5"));
        assert!(!md5("md5", "scram-sha-256"));
        assert!(!md5("scram-sha-256", "md5"));
        assert!(!md5("trust", "trust"));
    }

